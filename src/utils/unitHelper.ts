/**
 * שירות דיוק יחידות מידה לפי סוג המוצר עבור רשימת הקניות החכמה של PriceWise
 *
 * כללים מחייבים:
 * 1. בשר, עוף, דגים, ירקות ופירות שנמכרים לפי משקל: תמיד ק"ג (לדוגמה: "1 ק"ג" ולא "1 ליטר" או "1 יחידה").
 * 2. נוזלים ושתייה (חלב, שמן, שתייה קלה): ליטר או מ"ל (ולא "1 יחידה").
 * 3. מוצרים ארוזים (חמאה, גבינות, קוטג', קופסאות, פסטה, תבלינים): יחידה או גרם (ולא "1 ליטר").
 * 4. ביצים: תבנית.
 * 5. שישיות/מארזים: מארז או שישייה.
 */

export function getAccurateProductUnit(productName: string, existingUnit?: string): string {
  const name = (productName || '').trim().toLowerCase();
  const rawUnit = (existingUnit || '').trim().toLowerCase();

  // 1. ביצים -> תבנית
  if (/ביצ(?:ים|ה)|תבנית ביצים/i.test(name)) {
    return 'תבנית';
  }
  if (/תבנית/i.test(rawUnit)) {
    return 'תבנית';
  }

  // 2. שישיות / מארזים -> שישייה או מארז
  if (/שישיי(?:ה|ת)|שישיית/i.test(name) || /שישיי(?:ה|ת)/i.test(rawUnit)) {
    return 'שישייה';
  }
  if (/מארז|רביעיי(?:ה|ת)|שלישיי(?:ה|ת)|זוג\s+בקבוקים/i.test(name) || /מארז/i.test(rawUnit)) {
    return 'מארז';
  }

  // 3. בשר, עוף, דגים, ירקות ופירות שנמכרים לפי משקל -> תמיד ק"ג (או גרם אם מוגדר במפורש)
  const isProduceOrMeatOrFish =
    // בשר ועוף
    /בשר|עוף|חזה\s*עוף|פרגי(?:ת|ות)|כרעיים|שוקיים|כנפיים|בקר|אנטריקוט|סינטה|אסאדו|צלעות|טחון|כבש|הודו|קבב|אוסובוקו|כתף\s*בקר/i.test(name) ||
    // דגים
    /דג(?:ים)?|סלמון|אמנון|דניס|לברק|מושט|בורי|קרפיון|נסיכת\s*הנילוס|טונה\s*טריי?ה|פילה\s*דג/i.test(name) ||
    // ירקות
    /עגבני(?:ה|ות)|מלפפון|בצל|תפוח(?:\s*|י\s*)אדמה|גזר|קישוא|חציל|פלפל|שום|בטט(?:ה|ות)|כרוב|כרובית|ברוקולי|אבוקדו|פטריות|סלק|קולורבי|צנון|דלעת|דלורית|תרד|מנגולד/i.test(name) ||
    // פירות
    /תפוח(?:ים)?(?!\s*אדמה)|בננ(?:ה|ות)|תפוז(?:ים)?|קלמנטינ(?:ה|ות)|לימון(?:ים)?|אגס(?:ים)?|ענבים|אבטיח|מלון|תות(?:ים)?|שזיף(?:ים)?|אפרסק(?:ים)?|משמש|אפרשזיף|קיווי|פומלה|אשכולי(?:ת|ות)|מנגו|אגסים/i.test(name);

  if (isProduceOrMeatOrFish) {
    if (/גרם|גר'|ג'/i.test(rawUnit) || /\b(?:100|200|250|300|400|500|600|700|750|800)\s*גרם\b/i.test(name)) {
      return 'גרם';
    }
    // ברירת מחדל ותיקון שגיאות ("1 ליטר" או "1 יחידה" הופך לק"ג)
    return 'ק"ג';
  }

  // 4. נוזלים ושתייה (חלב, שמן, שתייה קלה) -> ליטר או מ"ל
  const isLiquidOrBeverage =
    // חלב ומוצרי שתייה
    /חלב|משקה\s*חלב|שוקו|אייס\s*קפה|רוויון/i.test(name) ||
    // שמנים
    /שמן|שמן\s*זית|שמן\s*קנולה|שמן\s*חמניות|שמן\s*סויה|שמן\s*תירס/i.test(name) ||
    // שתייה קלה ומשקאות
    /מים(?:\s*מינרליים)?|קולה|פפסי|ספרייט|פאנטה|מיץ|נקטר|תרכיז|סודה|בירה|יין|טמפו|משקה\s*קלה/i.test(name) ||
    // חומרי ניקוי נוזליים
    /ג['']?ל\s*כביסה|נוזל\s*כלים|מרכך\s*כביסה/i.test(name);

  if (isLiquidOrBeverage) {
    if (/מ["״]?ל|מל/i.test(rawUnit) || /\d+\s*מ["״]?ל/i.test(name)) {
      return 'מ"ל';
    }
    return 'ליטר';
  }

  // 5. מוצרים ארוזים (חמאה, גבינות, קוטג', קופסאות שימורים, פסטה, תבלינים) -> יחידה או גרם (ולא "1 ליטר")
  const isPackagedProduct =
    /חמאה|גבינ(?:ה|ות)|קוטג['׳]?|לאבנה|ריקוטה|מסקרפונה|פטה|בולגרית|צהובה|צפתית|שמנת\s*חמוצה|גבינת\s*שמנת/i.test(name) ||
    /פסטה|ספגטי|מקרוני|פתיתים|אטריות|לזניה|נודלס/i.test(name) ||
    /קופס(?:ה|ות|את)|שימורים|רסק\s*עגבניות|טונה\s*בשימורים|תירס\s*בשימורים|חמוצים|זיתים\s*בשימורים|עלי\s*גפן/i.test(name) ||
    /תבלין|פפריקה|כמון|מלח|פלפל\s*שחור|כורכום|זעתר|סוכר|קמח|אבקת\s*אפייה|סודה\s*לשתייה/i.test(name) ||
    /טחינה|חומוס|סלטים|ממרח|שוקולד|ופל|עוגיות|ביסקוויט|קרקר|שיבולת\s*שועל|קורנפלקס|דגני\s*בוקר|אורז/i.test(name) ||
    /לחם|פית(?:ה|ות)|לחמני(?:ה|ות)|חלה/i.test(name);

  if (isPackagedProduct) {
    if (/גרם|גר'|ג'/i.test(rawUnit) || /\d+\s*גרם/i.test(name)) {
      return 'גרם';
    }
    // לעולם לא "ליטר" עבור מוצרים ארוזים
    if (/ליטר|מ"ל/i.test(rawUnit)) {
      return 'יחידה';
    }
    return 'יחידה';
  }

  // התאמה כללית לפי היחידה הקיימת תוך וידוא שלא הוגדר "ליטר" בטעות למוצר מוצק
  if (/ק"ג|קג|קילו/i.test(rawUnit)) return 'ק"ג';
  if (/גרם|גר'|ג'/i.test(rawUnit)) return 'גרם';
  if (/ליטר/i.test(rawUnit)) return 'ליטר';
  if (/מ"ל|מל/i.test(rawUnit)) return 'מ"ל';
  if (/תבנית/i.test(rawUnit)) return 'תבנית';
  if (/מארז/i.test(rawUnit)) return 'מארז';
  if (/שישיי(?:ה|ת)/i.test(rawUnit)) return 'שישייה';
  if (/קופס(?:ה|אות)/i.test(rawUnit)) return 'קופסה';
  if (/חבילה|חב'/i.test(rawUnit)) return 'חבילה';
  if (/בקבוק/i.test(rawUnit)) return 'בקבוק';

  return 'יחידה';
}
